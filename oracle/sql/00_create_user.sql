-- Runs once, as SYS, when the Oracle container creates its database.
WHENEVER SQLERROR EXIT FAILURE
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER acme IDENTIFIED BY acme QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE,
      CREATE TRIGGER, CREATE SYNONYM, CREATE TYPE TO acme;
GRANT SELECT_CATALOG_ROLE TO acme;
EXIT
